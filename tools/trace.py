"""Requirements traceability report.

Reads every requirement ID from docs/02-requirements.md, runs both test suites,
matches tests to requirements by the ID in each test's name, and writes
docs/traceability.md. Exit code is non-zero if any automated test fails or any
requirement whose method includes T (test) has no test.

usage: python3 tools/trace.py
"""
from __future__ import annotations

import datetime
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REQ_RE = re.compile(r"^\|\s*(REQ-[A-Z]+-\d{3})\s*\|(.+?)\|(.+?)\|\s*([TADI/ ]+)\|", re.M)


def requirements():
    with open(os.path.join(ROOT, "docs", "02-requirements.md"), encoding="utf-8") as f:
        text = f.read()
    return [{"id": m[0], "text": m[1].strip(), "source": m[2].strip(), "method": m[3].strip()} for m in REQ_RE.findall(text)]


def run_js():
    files = sorted(os.path.join(ROOT, "tests", "js", f) for f in os.listdir(os.path.join(ROOT, "tests", "js")) if f.endswith(".test.js"))
    out = subprocess.run(["node", "--test", "--test-reporter=tap", *files], capture_output=True, text=True, cwd=ROOT)
    res = []
    for line in out.stdout.splitlines():
        m = re.match(r"^\s*(ok|not ok) \d+ - (REQ-[A-Z]+-\d{3})\s+(.*?)(\s+# TODO.*)?$", line)
        if m:
            status = "open" if m[4] else ("pass" if m[1] == "ok" else "fail")
            res.append({"req": m[2], "name": f"engine: {m[3]}", "status": status, "note": (m[4] or "").replace("# TODO", "").strip()})
    return res


def run_py():
    out = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", os.path.join(ROOT, "tests", "py"), "-v"],
                         capture_output=True, text=True, cwd=ROOT)
    res = []
    for line in out.stderr.splitlines():
        m = re.match(r"^(test_(REQ_[A-Z]+_\d{3})_\w+) \(.*?\)(?: \.\.\.)? (.*)$", line)
        if m:
            tail = m[3].strip()
            word = tail.split()[-1] if tail else ""
            skip = re.match(r"skipped ['\"](.*)['\"]$", tail)
            status = "open" if skip else "pass" if word == "ok" else "fail" if word in ("FAIL", "ERROR") else "unknown"
            res.append({"req": m[2].replace("_", "-"), "name": "service: " + m[1][5 + len(m[2]) + 1:].replace("_", " "), "status": status, "note": skip[1] if skip else ""})
    return res


def main():
    reqs = requirements()
    tests = run_js() + run_py()
    by_req = {}
    for t in tests:
        by_req.setdefault(t["req"], []).append(t)
    rows, problems = [], []
    counts = {"verified": 0, "open": 0, "failed": 0, "manual": 0, "missing": 0}
    for r in reqs:
        ts = by_req.get(r["id"], [])
        if ts:
            if any(t["status"] == "fail" for t in ts):
                st = "FAILED"; counts["failed"] += 1; problems.append(r["id"] + " failing")
            elif any(t["status"] == "open" for t in ts):
                st = "OPEN"; counts["open"] += 1
            else:
                st = "Verified (test)"; counts["verified"] += 1
        elif "T" in r["method"]:
            st = "NO TEST"; counts["missing"] += 1; problems.append(r["id"] + " has no test")
        else:
            st = "Manual (" + r["method"] + ")"; counts["manual"] += 1
        evidence = "<br>".join(f"{t['name']} — {t['status']}" + (f" ({t['note']})" if t["note"] else "") for t in ts) or "see 07-verification-plan.md"
        rows.append(f"| {r['id']} | {r['text']} | {r['method']} | {st} | {evidence} |")
    orphan = sorted(set(by_req) - {r["id"] for r in reqs})
    stamp = datetime.date.today().isoformat()
    md = [f"# Requirements traceability matrix", "",
          f"Generated by `tools/trace.py` on {stamp}. Do not edit by hand.", "",
          f"{len(reqs)} requirements: {counts['verified']} verified by test, {counts['open']} open, "
          f"{counts['failed']} failing, {counts['manual']} verified by inspection, demonstration or analysis, {counts['missing']} missing a test.", "",
          "| ID | Requirement | Method | Status | Evidence |", "| --- | --- | --- | --- | --- |", *rows, ""]
    if orphan:
        md += ["Tests referencing unknown requirement IDs: " + ", ".join(orphan), ""]
    with open(os.path.join(ROOT, "docs", "traceability.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print("\n".join(md[4:5]))
    for p in problems + [f"orphan test id {o}" for o in orphan]:
        print("  !", p)
    return 1 if problems or orphan else 0


if __name__ == "__main__":
    sys.exit(main())
